#!/usr/bin/env bash
# Build a fresh sample project and database in demo/.work.
#
#   seed.sh          the backlog as scene 1 finds it
#   seed.sh tui      the backlog as scene 3 finds it (after scenes 1 and 2 happened)
#   seed.sh claude   the base backlog plus the scree skill installed in the sample project
#
# Always starts from nothing, so every recording is reproducible.
set -euo pipefail

stage="${1:-base}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
rm -rf "$here/.work"
mkdir -p "$here/.work/shopfront"

# env.sh cds into the project, which does not exist as a repo yet.
git -C "$here/.work/shopfront" init -q -b main
git -C "$here/.work/shopfront" -c user.name=demo -c user.email=demo@example.com \
  commit -q --allow-empty -m "Initial commit"
# shellcheck source=env.sh
source "$here/env.sh"

human() { SCREE_ROLE=human SCREE_FORMAT=json scree "$@"; }
agent() { SCREE_ROLE=agent SCREE_FORMAT=json SCREE_AUTHOR="${AGENT_NAME:-claude}" SCREE_SESSION="${AGENT_SESSION:-sess-a}" scree "$@"; }
# add TITLE [flags...]: prints the new ticket id
add() { human add "$@" | jq -r .id; }

ci=$(add "Set up CI pipeline" --key SHOP --status ready)
search=$(add "Add product search endpoint" --status ready \
  --description "Full-text search over product name and description." \
  --criterion "GET /search?q= returns ranked results" \
  --criterion "Empty query returns 400" \
  --criterion "Index updates when a product changes")
results=$(add "Build search results page" --status ready --blocked-by "$search" \
  --description "Show hits from the search endpoint with pagination.")
add "Fix cart total rounding bug" --status ready \
  --description "Totals drift by a cent when a discount applies to several line items." >/dev/null
provider=$(add "Choose a payment provider" --status ready --for human \
  --description "Compare fees and payout times, then pick one.")
add "Checkout with card payments" --status ready --blocked-by "$provider" >/dev/null
add "Rate limit the public API" >/dev/null
add "Dark mode" >/dev/null
sessions=$(add "Migrate sessions to Redis" --status ready \
  --criterion "Sessions survive an app restart" \
  --criterion "Old cookies are still accepted" \
  --criterion "Load test shows no regression")

human done "$ci" >/dev/null

# One ticket already in flight by another agent, so the board has an Active column.
AGENT_NAME=claude AGENT_SESSION=sess-a agent start "$sessions" >/dev/null
AGENT_NAME=claude AGENT_SESSION=sess-a agent check "${sessions}#1" \
  --evidence "restart test passes" >/dev/null

if [ "$stage" = "tui" ]; then
  # What scenes 1 and 2 leave behind.
  add "Add a wishlist page" --status ready --blocked-by "$results" >/dev/null
  AGENT_NAME=claude AGENT_SESSION=sess-b agent start "$search" >/dev/null
  for n in 1 2 3; do
    AGENT_NAME=claude AGENT_SESSION=sess-b agent check "${search}#${n}" \
      --evidence "covered by tests" >/dev/null
  done
  AGENT_NAME=claude AGENT_SESSION=sess-b agent done "$search" >/dev/null
fi

if [ "$stage" = "claude" ]; then
  # Project-level skill, generated by the binary being demoed so it always matches.
  mkdir -p "$here/.work/shopfront/.claude/skills/scree"
  scree skill > "$here/.work/shopfront/.claude/skills/scree/SKILL.md"
fi

echo "seeded ($stage): $SCREE_DB"
